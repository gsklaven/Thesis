def dataset_tables():
    matched = json.load(open(os.path.join(DS, "malware_dataset_matched.json"), encoding="utf-8"))
    src = {}
    for e in matched:
        src.setdefault(e["package_name"], source_name(e.get("source_code_path") or "") or "?")
    fp = json.load(open(os.path.join(DS, "excluded_malwarebench_false_positive.json"), encoding="utf-8"))
    fp_names = set(fp.get("false_positive", [])) | set(fp.get("mixed_versions", []))
    no_payload = json.load(open(os.path.join(DS, "excluded_no_payload_packages.json"), encoding="utf-8"))
    no_payload = set(no_payload if isinstance(no_payload, list) else no_payload.get("packages", no_payload))
    train, test = ra.names(os.path.join(DS, "rag_train")), ra.names(ra.MAL_DIR)
    group = lambda s: SOURCE_LABEL.get(s, s)
    order = []
    for s in ("pypi_malregistry", "pypi", "malware_samples", "malicious-software-packages-dataset", "maloss-samples"):
        if group(s) not in order:
            order.append(group(s))
    count = lambda names: Counter(group(src.get(n, "?")) for n in names)
    collected, fpc, npc = count(src), count(fp_names & set(src)), count(no_payload)
    trc, tec = count(train), count(test)
    rows = [f"{g} & {num(collected[g])} & {num(fpc[g] + npc[g])} & {num(trc[g])} & {num(tec[g])}" for g in order]
    rows += ["\\hline", f"Σύνολο & {num(len(src))} & {num(len((fp_names | no_payload) & set(src)))} & "
             f"{num(len(train))} & {num(len(test))}"]
    write("dataset_sources.tex", table(
        "Δείγματα κακόβουλων πακέτων ανά πηγή: συλλογή, εξαίρεση και τελική κατανομή στο ευρετήριο "
        "(εκπαίδευση) και στο σύνολο αξιολόγησης.", "tab:dataset_sources", "|l|r|r|r|r|",
        "Πηγή & Δείγματα & Εξαιρέθηκαν & Ευρετήριο & Αξιολόγηση", rows,
        note="Εξαιρέθηκαν: νόμιμα πακέτα με λανθασμένη ετικέτα malware και πακέτα χωρίς κακόβουλο "
             "κώδικα (Ενότητα~\\ref{subsection:label_quality})."))

    # final sets: packages / with chains / chains, from the reports of the full system
    R = ra.load("v12_sum")
    ben = ra.names(ra.BEN_DIR)
    meta = json.load(open(os.path.join(DS, "indexes", "rag_index", "metadata.json"), encoding="utf-8"))
    index_chains = len(meta) if isinstance(meta, list) else len(meta.get("entries", meta))
    with_chains = lambda S: [n for n in S if R.get(n, {}).get("final_verdict") != "NO_CHAINS_FOUND"]
    chains = lambda S: sum(R[n].get("total_chains_analyzed") or 0 for n in S if n in R)
    rows = [f"Ευρετήριο κακόβουλων δειγμάτων (εκπαίδευση) & {num(len(train))} & -- & {num(index_chains)}",
            f"Αξιολόγηση: κακόβουλα & {num(len(test))} & {num(len(with_chains(test)))} & {num(chains(test))}",
            f"Αξιολόγηση: νόμιμα & {num(len(ben))} & {num(len(with_chains(ben)))} & {num(chains(ben))}"]
    write("dataset_sets.tex", table(
        "Τα τελικά σύνολα δεδομένων.", "tab:dataset_sets", "|l|r|r|r|",
        "Σύνολο & Πακέτα & Με Behavior Chains & Behavior Chains", rows))

    rep = json.load(open(os.path.join(DS, "final_dataset_report.json"), encoding="utf-8"))
    dist = rep["final_attack_type_distribution"]
    rows = [f"\\texttt{{{k.replace('_', '\\_')}}} & {num(v)}" for k, v in sorted(dist.items(), key=lambda x: -x[1])]
    write("dataset_attack_types.tex", table(
        f"Ετικέτες τύπου επίθεσης των {num(rep['total_selected'])} επιλεγμένων κακόβουλων πακέτων "
        "(ένα πακέτο μπορεί να φέρει περισσότερες από μία ετικέτες).", "tab:attack_types", "|l|r|",
        "Ετικέτα & Πακέτα", rows))


