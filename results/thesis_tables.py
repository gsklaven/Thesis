    fig += [f"\\caption{{Confusion matrices των τεσσάρων διαμορφώσεων στο στάδιο του LLM. {legend}}}",
            "\\label{fig:confusion_grid}", "\\end{figure}"]
    write("confusion_grid.tex", fig)
    return res


